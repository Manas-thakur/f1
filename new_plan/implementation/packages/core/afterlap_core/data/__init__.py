"""AFTERLAP data module: adapters, ingestion, quality, recording and replay.

This package owns original source events. It converts vendor packets into
canonical :class:`~afterlap_contracts.TelemetryEvent` records and archives what
it could not map. It does not estimate, does not invent battery state, and does
not decide anything.

Entry points:

* :mod:`.adapters` -- ``SimulatorAdapter``, ``PublicReplayAdapter``,
  ``TeamFeedAdapter`` and the ``ObservationSource`` protocol a simulator must
  satisfy to be ingestible.
* :mod:`.pipeline` -- the ten ingestion stages and the router that assigns one
  monotonic session sequence across sources.
* :mod:`.quality` -- freshness from observation age and declared cadence, plus
  the energy ``integration_gap_s`` estimation uses to widen uncertainty.
* :mod:`.recording` -- Parquet chunks, atomic manifests, acquisition provenance
  and credential redaction.
* :mod:`.replay` -- the replay clock, seek-from-snapshot and session badges.
* :mod:`.backpressure` -- coalescing display buffers and lossless raw buffers.
"""

